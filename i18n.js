function curLang() {
  try {
    return state?.settings?.lang === "uk" ? "uk" : "ru";
  } catch { return "ru"; }
}
// Перевод строки интерфейса. Значение-функция вызывается с переданными аргументами.
function t(key, ...args) {
  const dict = I18N[curLang()] || I18N.ru;
  let v = dict[key];
  if (v === undefined) v = I18N.ru[key];
  if (v === undefined) return key;
  return typeof v === "function" ? v(...args) : v;
}
function pickRandom(key) {
  const arr = t(key);
  return Array.isArray(arr) && arr.length ? arr[Math.floor(Math.random() * arr.length)] : "";
}
// Название упражнения для показа. Внутри данных ключ всегда остаётся русским.
function exName(name) {
  return curLang() === "uk" ? (EX_NAMES_UK[name] || name) : name;
}
function dayLabel(name) {
  return curLang() === "uk" ? (DAY_NAMES_UK[name] || name) : name;
}
function blockLabel(name) {
  if (curLang() !== "uk") return name;
  const week = /^Неделя\s+(\d+)$/.exec(name || "");
  if (week) return `Тиждень ${week[1]}`;
  return BLOCK_NAMES_UK[name] || name;
}
function programLabel(prog) {
  return curLang() === "uk" ? (PROGRAM_NAMES_UK[prog.id] || prog.name) : prog.name;
}
// Схемы и отдых — короткие строки из данных программы: только "мин" и "либо"
// требуют перевода, остальное (цифры, ×, Дропсет, Суперсет) одинаково.
function fmtScheme(s) {
  if (curLang() !== "uk" || !s) return s;
  return String(s).replace(/мин/g, "хв").replace(/либо/g, "або").replace(/Либо/g, "Або");
}
function fmtRest(r) {
  return fmtScheme(r);
}
function localeTag() {
  return curLang() === "uk" ? "uk-UA" : "ru-RU";
}
